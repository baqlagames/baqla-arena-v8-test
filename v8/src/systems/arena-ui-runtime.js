import { createBattleHudRuntime } from '../ui/battle-hud-runtime.js';
import { createManagePanelInputHandler } from '../ui/manage-panel-input.js';
import { createManagePanelRenderer } from '../ui/manage-panel-screen.js';
import { createUnitPickerRuntime } from '../ui/unit-picker-runtime.js';

export function createArenaUiRuntime(deps = {}) {
  const unitPickerRuntime = createUnitPickerRuntime({
    ctx: deps.ctx,
    playerUnits: deps.playerUnits,
    vodka: deps.vodka,
    attackTypeByUnit: deps.attackTypeByUnit,
    rootOrder: deps.rootOrder,
    roleRoot: deps.roleRoot,
    canPlace: deps.canPlace,
    unitGoldCost: deps.unitGoldCost,
    getStats: deps.getStats,
    placeUnit: deps.placeUnit,
    inRect: deps.inRect,
    showFlash: deps.showFlash,
    getTouchAccumY: deps.getTouchAccumY,
    setTouchAccumY: deps.setTouchAccumY,
    view: deps.pickerView,
  });

  const managePanelRenderer = createManagePanelRenderer({
    ctx: deps.ctx,
    playerUnits: deps.playerUnits,
    vodka: deps.vodka,
    unitBranches: deps.unitBranches,
    maxUnitLevel: deps.maxUnitLevel,
    baseSignatures: deps.baseSignatures,
    branchSignatures: deps.branchSignatures,
    sellRefundForCell: deps.sellRefundForCell,
    view: deps.managePanelView,
    isRoleRootCell: deps.isRoleRootCell,
    roleSpecs: deps.roleSpecs,
    specById: deps.specById,
    cellPathMeta: deps.cellPathMeta,
    roleRoot: deps.roleRoot,
    drawSkillSlots: deps.drawSkillSlots,
    getStats: deps.getStats,
    upgradeCostFor: deps.upgradeCostFor,
    pathUpgradeCost: deps.pathUpgradeCost,
    pathDetails: deps.pathDetails,
    baseSpec: deps.baseSpec,
    sigDisplayFc: deps.sigDisplayFc,
    sigDisplayCd: deps.sigDisplayCd,
    baseHeadline: deps.baseHeadline,
    branchHeadline: deps.branchHeadline,
    nextUnlockBrief: deps.nextUnlockBrief,
    wrapTextClamped: deps.wrapTextClamped,
  });

  const managePanelInputHandler = createManagePanelInputHandler({
    arenaState: deps.arenaState,
    unitBranches: deps.unitBranches,
    specById: deps.specById,
    upgradeCell: deps.upgradeCell,
    sellCell: deps.sellCell,
    showFlash: deps.showFlash,
  });

  const battleHudRuntime = createBattleHudRuntime({
    ctx: deps.ctx,
    abilities: deps.abilities,
    playerUnits: deps.playerUnits,
    vodka: deps.vodka,
    tickHz: deps.tickHz,
    bloodlustCost: deps.bloodlustCost,
    tranquilityCost: deps.tranquilityCost,
    gridCols: deps.gridCols,
    gridRows: deps.gridRows,
    gridX: deps.gridX,
    gridY: deps.gridY,
    cellW: deps.cellW,
    cellH: deps.cellH,
    view: deps.battleHudView,
    setBossWarning: deps.setBossWarning,
    drawBattleHudOverlay: deps.drawBattleHudOverlay,
    renderProjectedBuildGrid: deps.renderProjectedBuildGrid,
    drawBuildGrid: deps.drawBuildGrid,
    drawEncounterPurifyBar: deps.drawEncounterPurifyBar,
    drawEncounterLieutenantsBar: deps.drawEncounterLieutenantsBar,
    drawEncounterBossHpBar: deps.drawEncounterBossHpBar,
    drawEncounterBossCastBar: deps.drawEncounterBossCastBar,
    renderHudRgb: deps.renderHudRgb,
    renderHudShade: deps.renderHudShade,
    renderDrawHudPanel: deps.renderDrawHudPanel,
    renderFitCanvasText: deps.renderFitCanvasText,
    renderDrawHudMeter: deps.renderDrawHudMeter,
    renderDrawHudIcon: deps.renderDrawHudIcon,
    drawRoundReportChip: deps.drawRoundReportChip,
    getResultButtonRects: deps.getResultButtonRects,
    drawResultCombatReportPanel: deps.drawResultCombatReportPanel,
    getRoundCombatReport: deps.getRoundCombatReport,
    getStageCombatReport: deps.getStageCombatReport,
    drawMobileBattleControls: deps.drawMobileBattleControls,
    drawBattleTopChrome: deps.drawBattleTopChrome,
    drawDesktopBattleControls: deps.drawDesktopBattleControls,
    drawPauseMenu: deps.drawPauseMenu,
    threatPanelHeight: deps.threatPanelHeight,
    statsFormat: deps.statsFormat,
    currentStageRounds: deps.currentStageRounds,
    cellScreenQuad: deps.cellScreenQuad,
    cellScreenPoint: deps.cellScreenPoint,
    drawThreatsPanel: deps.drawThreatsPanel,
    drawPicker: () => unitPickerRuntime.drawPicker(),
    drawManagePanel: () => managePanelRenderer.drawManagePanel(),
    isCapstoneLevel: deps.isCapstoneLevel,
    pathCamQuad: deps.pathCamQuad,
    camPoint: deps.camPoint,
    camDepthScaleAt: deps.camDepthScaleAt,
  });

  return {
    drawBattleHud: (...args) => battleHudRuntime.drawBattleHud(...args),
    arena_drawProjectedBuildGrid: (...args) => battleHudRuntime.arena_drawProjectedBuildGrid(...args),
    arena_drawGrid: (...args) => battleHudRuntime.arena_drawGrid(...args),
    arena_drawPurifyBar: (...args) => battleHudRuntime.arena_drawPurifyBar(...args),
    arena_drawLieutenantsBar: (...args) => battleHudRuntime.arena_drawLieutenantsBar(...args),
    arena_drawBossHpBar: (...args) => battleHudRuntime.arena_drawBossHpBar(...args),
    arena_drawBossCastBar: (...args) => battleHudRuntime.arena_drawBossCastBar(...args),
    arena_hudRgb: (...args) => battleHudRuntime.arena_hudRgb(...args),
    arena_hudShade: (...args) => battleHudRuntime.arena_hudShade(...args),
    arena_hudPanel: (...args) => battleHudRuntime.arena_hudPanel(...args),
    arena_hudFitText: (...args) => battleHudRuntime.arena_hudFitText(...args),
    arena_drawHudMeter: (...args) => battleHudRuntime.arena_drawHudMeter(...args),
    arena_drawHudIcon: (...args) => battleHudRuntime.arena_drawHudIcon(...args),
    arena_drawCombatRoundChip: (...args) => battleHudRuntime.arena_drawCombatRoundChip(...args),
    arena_resultButtonRects: (...args) => battleHudRuntime.arena_resultButtonRects(...args),
    arena_drawCombatReportPanel: (...args) => battleHudRuntime.arena_drawCombatReportPanel(...args),
    arena_drawRoundCombatReport: (...args) => battleHudRuntime.arena_drawRoundCombatReport(...args),
    arena_drawStageCombatReport: (...args) => battleHudRuntime.arena_drawStageCombatReport(...args),
    arena_drawMobileBattleHud: (...args) => battleHudRuntime.arena_drawMobileBattleHud(...args),
    arena_drawHud: (...args) => battleHudRuntime.arena_drawHud(...args),
    arena_drawPauseMenu: (...args) => battleHudRuntime.arena_drawPauseMenu(...args),
    pickerCardCount: () => unitPickerRuntime.cardCount(),
    pickerMaxScroll: () => unitPickerRuntime.maxScroll(),
    pickerDeck: () => unitPickerRuntime.deck(),
    pickerEntries: () => unitPickerRuntime.entries(),
    drawPicker: () => unitPickerRuntime.drawPicker(),
    handlePickerClick: point => unitPickerRuntime.handleClick(point),
    drawManagePanel: () => managePanelRenderer.drawManagePanel(),
    handleManagePanelClick: point => managePanelInputHandler.handleClick(point),
  };
}
