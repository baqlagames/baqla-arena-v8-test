export function createUnitUpdateRuntime(deps) {
  function updateUnit(u){
    const {arena,units,enemies,projectiles,bombs,groundFx,beamFx,frame,arenaLeft:ARENA_L,arenaRight:ARENA_R,arenaTop:ARENA_TOP,arenaBottom:ARENA_BOT}=deps.view();
    const GAME_TICK_HZ=deps.tickHz;
    const ABILITIES=deps.abilities;
    const SFX=deps.sound;
    const rnd=deps.randomRange;
    const addP=deps.emitParticle;
    const addDmg=deps.addDamageText;
    const addHealFx=deps.addHealEffect;
    const {
      updateGhostUnit,moveToward,dealDamage,tickUnitUpkeep,tickUnitEarlyActions,tickUnitStatusTimers,
      tickUnitMeteorAndSignature,setSignatureBanner,tickUnitWarlockPassives,tickUnitHunterPassives,
      tickUnitRummanPassives,tickUnitCompanionPassives,tickUnitBranchPassives,tickUnitPriestPassives,
      tickUnitZaytBakdounesPassives,tickUnitHabaqPassives,tickUnitSignatureBuffTimers,tickUnitActionTimers,
      tickUnitPlagueAndJazarPassives,tickUnitAlibabaPassives,tickUnitHealerAuraPassives,tickUnitSupportAndGapClosers,
      prepareUnitAttackTarget,prepareUnitAttack,applyEarlyOnHitProcs,applyZaytOnHitProcs,applyJazarOnHitProcs,
      applyAlibabaOnHitProcs,applyNaanaFoulFelfelOnHitProcs,applyJafaarOnHitProcs,applyZaatarOnHitProcs,
      dispatchUnitBasicAttack,applyCoreFamilyOnHitProcs,applyGenericOnHitProcs,applyRummanOnHitProcs,
      applyPostHitSupportProcs,clampToArena,arena_clampToLeash,arena_applyTrackedHeal,
      arena_taoonBloodTithe,arena_addTaoonBloodShield,arena_applyMuddied,arena_healerTriageTick,
      arena_addZavsLineShield,arena_applyHealingReceived,arena_findJafaarDrainTarget,
      arena_jafaarCurseWeight,arena_applyJafaarAgony,fireProjectile,
      findEnemyForUnit,findRangedEnemyForUnit,arena_findLowestAlly,arena_drainHealToBarrier,
      arena_beaconSplash,arena_addGoldShield,arena_isGripReserved,arena_isGapCloserReserved,
      arena_reserveGripTarget,arena_reserveGapCloserTarget,arena_grantGapInvulnerability,
      arena_jazarGuard,arena_jazarSignatureSurge,arena_findBestEnemyClusterPoint,
      arena_findUnreservedEnemyInRange,arena_followFamiliarAnchor,arena_isReachable,
      arena_allyDmgMult,arena_zavsAllyAtkSpdFactor,advanceSharedOnHitCounter,
      arena_moonkinControlBurst,arena_moonkinDisplaceEnemy,arena_fireDivineStorm,
      arena_applyFelfelDeadlyPoison,arena_findBasicSecondTarget,arena_basicSecondHitFor,
      arena_applyRuneWound,arena_isTaoonPriorityEnemy,arena_addBatataShield,
      arena_isBatataBacklineAlly,arena_isZavsMeleeAlly,lobBomb,arena_findEmergencyTarget,
      showFlash
    }=deps;
    const activePerkEffects=typeof deps.perkEffects==='function'?deps.perkEffects()||{}:{};

  if(u.hp<=0)return;
  if(u.familiar&&(!u.parent||u.parent.hp<=0)){u.hp=0;u.removed=true;return}
  if(updateGhostUnit(u,{enemies,moveToward,dealDamage,emitParticle:addP,groundEffects:groundFx,addDamageText:addDmg,shake:value=>{deps.shake(value);}}))return;
  if(arena.phase==='build'){
    if(u.homeX!=null){u.x=u.homeX;u.y=u.homeY}
    return;
  }
  tickUnitUpkeep(u,{
    frame,
    units,
    enemies,
    randomRange:rnd,
    groundEffects:groundFx,
    beamFx,
    dealDamage,
    applyTrackedHeal:arena_applyTrackedHeal,
    applyTaoonBloodTithe:arena_taoonBloodTithe,
    addTaoonBloodShield:arena_addTaoonBloodShield,
    applyMuddied:arena_applyMuddied,
    clampToArena,
    healerTriageTick:arena_healerTriageTick,
    emitParticle:addP,
    addDamageText:addDmg,
  });
  if(tickUnitEarlyActions(u,{
    frame,
    enemies,
    units,
    abilities:ABILITIES,
    arenaTop:ARENA_TOP,
    randomRange:rnd,
    beamFx,
    groundEffects:groundFx,
    dealDamage,
    clampToLeash:arena_clampToLeash,
    addZavsLineShield:arena_addZavsLineShield,
    emitParticle:addP,
    addDamageText:addDmg,
    showFlash,
    sound:SFX,
    shake:value=>{deps.shake(value);}
  }))return;
  if(tickUnitStatusTimers(u,{
    frame,
    randomRange:rnd,
    groundEffects:groundFx,
    dealDamage,
    emitParticle:addP,
    addDamageText:addDmg
  }))return;
  const banner=tickUnitMeteorAndSignature(u,{
    frame,
    enemies,
    bombs,
    arenaTop:ARENA_TOP,
    perkEffects: activePerkEffects,
    randomRange:rnd,
    groundEffects:groundFx,
    emitParticle:addP,
    addDamageText:addDmg
  });
  if(banner)setSignatureBanner(banner);
  tickUnitWarlockPassives(u,{
    frame,
    units,
    enemies,
    randomRange:rnd,
    beamFx,
    groundEffects:groundFx,
    dealDamage,
    findDrainTarget:arena_findJafaarDrainTarget,
    curseWeight:arena_jafaarCurseWeight,
    applyAgony:arena_applyJafaarAgony,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  tickUnitHunterPassives(u,{
    frame,
    enemies,
    randomRange:rnd,
    fireProjectile,
    emitParticle:addP,
    addDamageText:addDmg
  });
  if(tickUnitRummanPassives(u,{
    frame,
    units,
    enemies,
    arenaTop:ARENA_TOP,
    randomRange:rnd,
    groundEffects:groundFx,
    dealDamage,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  }))return;
  tickUnitCompanionPassives(u,{
    frame,
    units,
    enemies,
    randomRange:rnd,
    groundEffects:groundFx,
    dealDamage,
    applyHealingReceived:arena_applyHealingReceived,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  tickUnitBranchPassives(u,{
    frame,
    units,
    enemies,
    randomRange:rnd,
    groundEffects:groundFx,
    applyHealingReceived:arena_applyHealingReceived,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  if(tickUnitPriestPassives(u,{
    frame,
    units,
    enemies,
    projectiles,
    beamEffects:beamFx,
    arena,
    randomRange:rnd,
    groundEffects:groundFx,
    dealDamage,
    applyHealingReceived:arena_applyHealingReceived,
    addHealFx,
    findEnemyForUnit,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  }))return;
  tickUnitZaytBakdounesPassives(u,{
    frame,
    units,
    enemies,
    projectiles,
    beamEffects:beamFx,
    randomRange:rnd,
    groundEffects:groundFx,
    dealDamage,
    findLowestAlly:arena_findLowestAlly,
    applyTrackedHeal:arena_applyTrackedHeal,
    beaconSplash:arena_beaconSplash,
    addHealFx,
    showFlash,
    playShieldBlock:()=>SFX.shieldBlock(),
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  tickUnitHabaqPassives(u,{
    frame,
    units,
    projectiles,
    beamEffects:beamFx,
    randomRange:rnd,
    groundEffects:groundFx,
    applyTrackedHeal:arena_applyTrackedHeal,
    emitParticle:addP,
    addDamageText:addDmg,
  });
  tickUnitSignatureBuffTimers(u,{
    frame,
    units,
    enemies,
    arena,
    groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    drainHealToBarrier:arena_drainHealToBarrier,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    showFlash,
    shake:value=>{deps.shake(value);}
  });
  tickUnitActionTimers(u,{
    frame,
    enemies,
    beamEffects:beamFx,
    groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    fireProjectile,
    clampToArena,
    clampToLeash:arena_clampToLeash,
    isGripReserved:arena_isGripReserved,
    isGapCloserReserved:arena_isGapCloserReserved,
    isTaoonPriorityEnemy:arena_isTaoonPriorityEnemy,
    reserveGripTarget:arena_reserveGripTarget,
    grantGapInvulnerability:arena_grantGapInvulnerability,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    showFlash,
    playStealth:()=>SFX.stealth(),
    playHeavySlash:()=>SFX.heavySlash(),
    playBackstab:()=>SFX.backstab(),
    playFrostBolt:()=>SFX.frostBolt(),
    shake:value=>{deps.shake(value);}
  });
  tickUnitPlagueAndJazarPassives(u,{
    frame,
    units,
    enemies,
    beamEffects:beamFx,
    groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    clampToArena,
    clampToLeash:arena_clampToLeash,
    grantJazarGuard:arena_jazarGuard,
    triggerJazarSignatureSurge:arena_jazarSignatureSurge,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    showFlash,
    playHeavySlash:()=>SFX.heavySlash(),
    shake:value=>{deps.shake(value);}
  });
  tickUnitAlibabaPassives(u,{
    frame,
    enemies,
    arenaBounds:{left:ARENA_L,right:ARENA_R,top:ARENA_TOP,bottom:ARENA_BOT},
    groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    findBestEnemyClusterPoint:arena_findBestEnemyClusterPoint,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  // Living Bomb (Fire Lord sig) Ã¢â‚¬â€ tick on enemies
  // (handled in enemy tick section)
  // Cauterize Ã¢â‚¬â€ death hook (revive once)
  // (handled in death hook section)
  tickUnitHealerAuraPassives(u,{
    frame,units,enemies,projectiles,
    beamEffects:beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    applyTrackedHeal:arena_applyTrackedHeal,
    drainHealToBarrier:arena_drainHealToBarrier,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg
  });
  if(tickUnitSupportAndGapClosers(u,{
    arena,frame,units,enemies,
    arenaTop:ARENA_TOP,
    beamEffects:beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    clampToArena,
    clampToLeash:arena_clampToLeash,
    addGoldShield:arena_addGoldShield,
    isGripReserved:arena_isGripReserved,
    isGapCloserReserved:arena_isGapCloserReserved,
    reserveGapCloserTarget:arena_reserveGapCloserTarget,
    reserveGripTarget:arena_reserveGripTarget,
    findUnreservedEnemyInRange:arena_findUnreservedEnemyInRange,
    grantGapInvulnerability:arena_grantGapInvulnerability,
    showFlash,
    emitParticle:addP,
    addDamageText:addDmg,
    sound:SFX,
    shake:value=>{deps.shake(value);}
  }))return;
  const attackTargeting=prepareUnitAttackTarget(u,{
    arena,
    enemies,
    frame,
    arenaTop:ARENA_TOP,
    arenaBottom:ARENA_BOT,
    randomRange:rnd,
    findRangedEnemyForUnit,
    findEnemyForUnit,
    followFamiliarAnchor:arena_followFamiliarAnchor,
    isReachable:arena_isReachable,
    moveToward,
    clampToArena,
    clampToLeash:arena_clampToLeash,
    beamFx,
    groundEffects:groundFx,
    emitParticle:addP,
    addDamageText:addDmg,
    sound:SFX,
    shake:value=>{deps.shake(value);}
  });
  if(!attackTargeting.canAttack)return;
  let t=attackTargeting.target;
  if(u.cd>0)return;
  // Drain Life channeling Ã¢â‚¬â€ skip basic attacks while channeling
  if(u._drainChanneling)return;
  // Rapid Fire channeling Ã¢â‚¬â€ skip basic attacks while channeling
  if(u._rapidChanneling)return;
  // Void Torrent channeling Ã¢â‚¬â€ skip basic attacks while channeling
  if(u._voidTorrent)return;
  const attackPrep=prepareUnitAttack(u,t,{
    arena,
    enemies,
    allyDamageMultiplier:arena_allyDmgMult,
    allyAttackSpeedFactor:arena_zavsAllyAtkSpdFactor,
    advanceSharedOnHitCounter,
    groundEffects:groundFx,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  const _ohTier=attackPrep.ohTier;
  const _allyMult=attackPrep.allyMult;
  const isEmpower=attackPrep.isEmpower;
  const isCrit=attackPrep.isCrit;
  const isExecute=attackPrep.isExecute;
  const firstStrike=attackPrep.firstStrike;
  let dmg=attackPrep.damage;
  let isAimed=attackPrep.isAimed;
  const earlyOnHit=applyEarlyOnHitProcs(u,t,{
    arena,frame,
    ohTier:_ohTier,
    damage:dmg,
    units,enemies,projectiles,
    beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    findLowestAlly:arena_findLowestAlly,
    applyTrackedHeal:arena_applyTrackedHeal,
    moonkinControlBurst:arena_moonkinControlBurst,
    moonkinDisplaceEnemy:arena_moonkinDisplaceEnemy,
    showFlash,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  dmg=earlyOnHit.damage;
  applyZaytOnHitProcs(u,t,{
    arena,frame,
    ohTier:_ohTier,
    damage:dmg,
    isCrit,
    units,enemies,projectiles,
    beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    fireDivineStorm:arena_fireDivineStorm,
    addGoldShield:arena_addGoldShield,
    applyHealingReceived:arena_applyHealingReceived,
    beaconSplash:arena_beaconSplash,
    findLowestAlly:arena_findLowestAlly,
    soundEffects:SFX,
    showFlash,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  applyJazarOnHitProcs(u,t,{
    frame,
    ohTier:_ohTier,
    enemies,
    beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    clampToArena,
    grantJazarGuard:arena_jazarGuard,
    showFlash,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  applyAlibabaOnHitProcs(u,t,{
    frame,
    ohTier:_ohTier,
    damage:dmg,
    enemies,
    beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    showFlash,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  applyNaanaFoulFelfelOnHitProcs(u,t,{
    frame,
    ohTier:_ohTier,
    damage:dmg,
    enemies,
    beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    applyFelfelDeadlyPoison:arena_applyFelfelDeadlyPoison,
    showFlash,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  applyJafaarOnHitProcs(u,t,{
    frame,
    ohTier:_ohTier,
    damage:dmg,
    units,enemies,bombs,
    beamFx,groundEffects:groundFx,
    randomRange:rnd,
    dealDamage,
    applyJafaarAgony:arena_applyJafaarAgony,
    findBasicSecondTarget:arena_findBasicSecondTarget,
    showFlash,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  const zaatarOnHit=applyZaatarOnHitProcs(u,t,{
    frame,
    ohTier:_ohTier,
    damage:dmg,
    isAimed,
    units,enemies,
    beamFx,groundEffects:groundFx,
    dealDamage,
    showFlash,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  isAimed=zaatarOnHit.isAimed;
  dispatchUnitBasicAttack(u,t,{
    damage:dmg,
    allyMult:_allyMult,
    isAimed,
    isCrit,
    firstStrike,
    isExecute,
    isEmpower,
  },{
    frame,
    enemies,
    units,
    randomRange:rnd,
    beamFx,
    groundEffects:groundFx,
    basicSecondHitFor:arena_basicSecondHitFor,
    findBasicSecondTarget:arena_findBasicSecondTarget,
    fireProjectile,
    dealDamage,
    addHealFx,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  if(activePerkEffects.openingStunDur&&!u._perkStunUsed&&t&&t.hp>0&&!t.isBoss){
    t.stunned=Math.max(t.stunned||0,Math.round(activePerkEffects.openingStunDur));
    u._perkStunUsed=true;
    addP(t.x,t.y,'#60a5fa',12,4);
    addDmg(t.x,t.y-t.size-4,'STUN SEED','#60a5fa',{sz:12,bold:true});
  }
  applyCoreFamilyOnHitProcs(u,t,{
    ohTier:_ohTier,
    damage:dmg,
    units,
    enemies,
    beamFx,
    groundEffects:groundFx,
    dealDamage,
    applyRuneWound:arena_applyRuneWound,
    isTaoonPriorityEnemy:arena_isTaoonPriorityEnemy,
    applyTrackedHeal:arena_applyTrackedHeal,
    applyTaoonBloodTithe:arena_taoonBloodTithe,
    addTaoonBloodShield:arena_addTaoonBloodShield,
    addBatataShield:arena_addBatataShield,
    isBatataBacklineAlly:arena_isBatataBacklineAlly,
    isZavsMeleeAlly:arena_isZavsMeleeAlly,
    applyMuddied:arena_applyMuddied,
    emitParticle:addP,
    addDamageText:addDmg,
    sound:SFX,
    shake:value=>{deps.shake(value);}
  });
  applyGenericOnHitProcs(u,t,{
    frame,
    damage:dmg,
    isAimed,
    enemies,
    beamFx,
    groundEffects:groundFx,
    dealDamage,
    clampToArena,
    emitParticle:addP,
    addDamageText:addDmg,
    shake:value=>{deps.shake(value);}
  });
  applyRummanOnHitProcs(u,t,{
    ohTier:_ohTier,
    damage:dmg,
    units,
    enemies,
    beamFx,
    groundEffects:groundFx,
    dealDamage,
    randomRange:rnd,
    emitParticle:addP,
    addDamageText:addDmg,
    showFlash,
    shake:value=>{deps.shake(value);}
  });
  applyPostHitSupportProcs({
    unit:u,target:t,damage:dmg,frame,units,enemies,beamEffects:beamFx,
    emitParticle:addP,addDamageText:addDmg,addHealFx,showFlash,lobBomb,
    findLowestAlly:arena_findLowestAlly,
    findEmergencyTarget:arena_findEmergencyTarget,
    drainHealToBarrier:arena_drainHealToBarrier,
    beaconSplash:arena_beaconSplash,
    shake:value=>{deps.shake(value);}
  });
  u.bobPhase+=0.06;

  }
  return {updateUnit};
}
